/**
 * 종목 한 줄 설명 — "이 회사가 뭐 하는 곳인지".
 *
 * ────────────────────────────────────────────────────────────────────
 *  왜 DB 가 아니라 코드인가
 * ────────────────────────────────────────────────────────────────────
 *
 * `company_profiles.description` 은 197/602 만 있고 전부 영문 원문이라 카드에
 * 넣을 수 없다. 그렇다고 한국어 요약을 그 테이블에 넣으면 다음 수집이 덮어쓴다
 * (yfinance 적재 대상이다). 별도 테이블을 만들면 마이그레이션 + 수집 스크립트
 * 수정 + db-snapshot 반영이 따라붙는데, **여기 담기는 건 사람이 쓴 짧은 문장**
 * 이라 데이터라기보다 문구에 가깝다.
 *
 * 코드에 두면:
 *   - 마이그레이션 0, 수집 파이프라인 수정 0
 *   - git diff 로 문장 변경이 리뷰된다(누가 언제 무엇을 고쳤는지)
 *   - 배포가 곧 반영 — db-snapshot 왕복이 없다
 *
 * `server-only` 라 클라이언트 번들에 들어가지 않는다. 서버가 필요한 종목의
 * 문장만 뽑아 응답에 실으므로, 목록이 커져도 브라우저가 받는 양은 그대로다.
 *
 * ────────────────────────────────────────────────────────────────────
 *  쓰는 규칙
 * ────────────────────────────────────────────────────────────────────
 *
 * - **40~60자.** 카드 한 줄에 들어가야 한다. 길면 truncate 되어 뒷말이 잘린다.
 * - **뭘 팔아 돈을 버는지**를 먼저 쓴다. 설립연도·본사·비전은 넣지 않는다.
 * - 섹터명을 되풀이하지 않는다("반도체 기업" ✕) — 섹터는 옆에 이미 붙는다.
 * - 없으면 비워 둔다. 화면은 섹터명으로 폴백하므로 빈칸이 생기지 않는다.
 *   **모르는 회사를 지어내지 않는 것이 비워 두는 것보다 나쁠 일은 없다.**
 */

