/** 한 줄 설명 조회. 없으면 null — 화면이 섹터명으로 폴백한다. */
export function getCompanySummary(ticker: string): string | null {
  return COMPANY_SUMMARIES[ticker] ?? null
}

/** 여러 종목을 한 번에. 목록 API 가 응답에 실을 때 쓴다. */
export function getCompanySummaries(
  tickers: readonly string[]
): Map<string, string> {
  const map = new Map<string, string>()
  for (const t of tickers) {
    const s = COMPANY_SUMMARIES[t]
    if (s) map.set(t, s)
  }
  return map
}

