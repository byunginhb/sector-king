/**
 * 기능 카탈로그 레지스트리 — **이 파일이 SoT 다.**
 *
 * ────────────────────────────────────────────────────────────────────
 *  규약
 * ────────────────────────────────────────────────────────────────────
 *
 * 1. `defaultPolicy` 는 **현재 배포된 실제 동작**이다. 지금 잠겨 있지 않은
 *    기능은 전부 `{ minTier: 'anon', gateMode: 'open' }` 이어야 한다.
 *    이 규칙 덕분에 이 시스템을 배포해도 사용자 화면이 바뀌지 않는다.
 *    기능을 새로 잠글 때는 게이트 코드와 이 기본값을 같은 커밋에 넣는다.
 *
 *    지금 `open` 이 아닌 항목은 **딱 세 부류뿐이고 전부 이미 배포된 가드다**:
 *      - `admin.*`            → `app/admin/layout.tsx` 의 `requireAdmin('/admin')`
 *      - `me.*` (/me 라우트)   → 각 페이지의 `requireUser(...)`
 *      - `news.*` 4건          → `components/news/locked-section.tsx` 비로그인 잠금
 *    이 목록은 `__tests__/unit/permissions-registry.test.ts` 의
 *    `PRE_GATED` 상수가 그대로 강제한다 — 여기에 없는 기능이 잠겨 있으면
 *    테스트가 깨지므로, 실수로 사용자 화면을 바꾸는 커밋이 통과하지 못한다.
 *
 * 1-b. `wired` 는 **그 기본값을 읽어 화면을 바꾸는 코드가 실제로 있는가**를
 *    가리킨다. 정책 저장은 언제나 즉시 반영되지만, `FeatureGate` 마운트와
 *    (`masking: 'server'` 인 경우) API 마스킹은 기능마다 따로 넣어야 하므로
 *    두 사실이 갈라진다. 갈라진 채로 콘솔이 스위치를 보여주면 운영자는
 *    "잠갔다" 고 믿고 실제로는 열려 있는 상태가 된다 — 그래서 배선 여부를
 *    레지스트리가 들고 콘솔이 배지로 드러낸다. 배선 커밋에서 `wired: true`
 *    를 게이트 코드와 **같은 커밋**에 넣는다. 현재 배선된 기능은 0건이다.
 *
 * 2. `recommendedMinTier` / `recommendedGateMode` 는 카탈로그 조사가 제안한
 *    값이며 **런타임 판정에 일절 관여하지 않는다.** 어드민 화면이 "제안"
 *    컬럼으로 보여주고, 운영자가 받아들이면 DB 오버라이드가 된다.
 *
 * 3. `featureId` 는 한 번 배포되면 바꾸지 않는다. 이름이 나빠졌으면 새 키를
 *    만들고 옛 키에 `retired: true` 를 단다 — 감사 로그가 옛 키를 참조한다.
 *
 * 4. 형식: `<namespace>.<feature>[-<qualifier>]`, `.` 은 정확히 하나.
 *    정규식은 `FEATURE_ID_PATTERN`. 네임스페이스는 URL 이 아니라 **제품면**
 *    기준이다 — `/rankings` 와 `/[industryId]/rankings` 는 둘 다 `rankings.*`.
 *
 * 5. `supportedGateModes: ['open']` 은 **잠금 봉인**이다. 카탈로그 §5
 *    "게이팅하면 안 되는 것"(SEO 착지면·법적 문서·로그인/수신거부·문의 창구·
 *    신뢰 문서)에 해당하는 기능은 어드민 셀렉트에서 `open` 외 선택지가
 *    아예 없다. 문서로만 적어 둔 금지 목록은 언젠가 반드시 어겨지므로,
 *    타입과 어드민 UI 가 강제하게 만든 것이 이 필드의 목적이다.
 *    반대로 `admin.*` 은 `['hidden']` 으로 고정한다 — 이미 `requireAdmin` 이
 *    지키고 있고 신규 시스템이 손대면 회귀 위험만 생긴다(카탈로그 §N).
 *
 * 전수 카탈로그 근거: `_workspace/01_plan/permission-catalog.md`
 * (페이지 50 라우트 + 비라우트 제품면 2 = 52, 기능 160)
 */

