export type FeatureId = keyof typeof FEATURES

/** 전체 featureId. 정렬은 페이지 순서 → 등록 순서. */
export const FEATURE_IDS: string[] = Object.keys(FEATURES)

export function getFeature(featureId: string): FeatureDef | undefined {
  return FEATURES[featureId]
}

export function getPage(pageId: string): PageDef | undefined {
  return PAGES.find((p) => p.id === pageId)
}

/** 한 페이지에 속한 기능들. 어드민 우측 표가 이 결과를 그린다. */
export function featuresByPage(pageId: string): Array<[string, FeatureDef]> {
  return Object.entries(FEATURES).filter(([, def]) => def.pageId === pageId)
}

/**
 * 게이트가 실제로 배선된 기능 (`FeatureDef.wired`).
 *
 * **현재 0건이다.** 이 시스템은 정책 저장·판정·미리보기까지를 담당하고,
 * 개별 화면에 `FeatureGate` 를 붙이고 API 에 서버 마스킹을 넣는 일은 기능마다
 * 별도 커밋으로 진행한다. 콘솔이 이 목록을 근거로 "설정해도 화면은 아직 안
 * 바뀝니다" 를 표시한다.
 */
export const WIRED_FEATURE_IDS: string[] = Object.entries(FEATURES)
  .filter(([, def]) => def.wired === true)
  .map(([id]) => id)
